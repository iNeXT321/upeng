package com.yt.agent.platform.persistence;

import lombok.extern.slf4j.Slf4j;

import javax.sql.DataSource;
import java.sql.Connection;
import java.sql.PreparedStatement;
import java.sql.ResultSet;
import java.sql.SQLException;
import java.sql.Statement;
import java.sql.Timestamp;
import java.util.ArrayList;
import java.util.List;

/**
 * JDBC 会话实现（H2 / PostgreSQL 通用）。
 *
 * <p>为什么手写 JDBC 而不是引入 JPA/MyBatis：这里只有一张追加写的时间序列表，
 * 引入 ORM 会带来实体管理、懒加载、方言适配等额外复杂度与依赖。手写 SQL 反而更透明，
 * 也避免了与主应用"排除 DataSourceAutoConfiguration"的现状冲突——
 * 数据源由本模块按需自建，不影响主链路启动。</p>
 *
 * <p>表结构设计要点：
 * <ul>
 *   <li>{@code turn_seq}：会话内序号，回放上下文的唯一顺序依据（不依赖时间戳，避免同毫秒乱序）；</li>
 *   <li>{@code tool_call_id}：工具结果与 assistant 的 tool_call 配对键。
 *       这是回放能否成功的关键——缺了它，模型会收到"孤儿工具结果"而报错；</li>
 *   <li>{@code meta}：JSON 扩展位，用于存放 toolCalls 列表等非固定结构，
 *       让表结构在框架升级时保持稳定。</li>
 * </ul>
 * </p>
 */
@Slf4j
public class JdbcSessionStore implements SessionStore {

    private final DataSource dataSource;
    private final String table;
    private final int maxTurnsPerSession;
    private final String backend;

    public JdbcSessionStore(DataSource dataSource, String tablePrefix, int maxTurnsPerSession, String backend) {
        this.dataSource = dataSource;
        this.table = sanitize(tablePrefix) + "session_turn";
        this.maxTurnsPerSession = Math.max(20, maxTurnsPerSession);
        this.backend = backend;
        initSchema();
    }

    private void initSchema() {
        String ddl = "CREATE TABLE IF NOT EXISTS " + table + " ("
                + "id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,"
                + "session_id VARCHAR(64) NOT NULL,"
                + "user_id VARCHAR(64),"
                + "turn_seq INT NOT NULL,"
                + "role VARCHAR(16) NOT NULL,"
                + "content TEXT,"
                + "tool_name VARCHAR(128),"
                + "tool_call_id VARCHAR(128),"
                + "meta TEXT,"
                + "created_at TIMESTAMP NOT NULL"
                + ")";
        String index = "CREATE INDEX IF NOT EXISTS idx_" + table + "_sid ON " + table + " (session_id, turn_seq)";
        try (Connection conn = dataSource.getConnection(); Statement st = conn.createStatement()) {
            st.execute(ddl);
            st.execute(index);
            log.info("[JdbcSessionStore] 会话表就绪: {} ({})", table, backend);
        } catch (SQLException e) {
            throw new IllegalStateException("初始化会话表失败: " + table + ", " + e.getMessage(), e);
        }
    }

    @Override
    public void append(String sessionId, String userId, List<ChatTurn> turns) {
        if (sessionId == null || turns == null || turns.isEmpty()) {
            return;
        }
        String insert = "INSERT INTO " + table
                + " (session_id,user_id,turn_seq,role,content,tool_name,tool_call_id,meta,created_at)"
                + " VALUES (?,?,?,?,?,?,?,?,?)";
        try (Connection conn = dataSource.getConnection()) {
            int base = nextSeq(conn, sessionId);
            long now = System.currentTimeMillis();
            try (PreparedStatement ps = conn.prepareStatement(insert)) {
                int seq = base;
                for (ChatTurn turn : turns) {
                    seq++;
                    ps.setString(1, sessionId);
                    ps.setString(2, userId);
                    ps.setInt(3, seq);
                    ps.setString(4, turn.getRole());
                    ps.setString(5, turn.getContent());
                    ps.setString(6, turn.getToolName());
                    ps.setString(7, turn.getToolCallId());
                    ps.setString(8, turn.getMeta());
                    ps.setTimestamp(9, new Timestamp(turn.getCreatedAt() == null ? now : turn.getCreatedAt()));
                    ps.addBatch();
                }
                ps.executeBatch();
            }
            trim(conn, sessionId, base + turns.size());
        } catch (SQLException e) {
            // 持久化失败不能拖垮主链路：对话已经产生，丢失历史可接受，但不能让用户拿不到答案
            log.error("[JdbcSessionStore] 写入会话失败 session={}, turns={}: {}",
                    sessionId, turns.size(), e.getMessage(), e);
        }
    }

    @Override
    public List<ChatTurn> load(String sessionId, int limit) {
        String sql = "SELECT turn_seq,role,content,tool_name,tool_call_id,meta,created_at FROM ("
                + "SELECT * FROM " + table + " WHERE session_id=? ORDER BY turn_seq DESC LIMIT ?"
                + ") t ORDER BY turn_seq ASC";
        List<ChatTurn> turns = new ArrayList<>();
        try (Connection conn = dataSource.getConnection();
             PreparedStatement ps = conn.prepareStatement(sql)) {
            ps.setString(1, sessionId);
            ps.setInt(2, Math.max(1, limit));
            try (ResultSet rs = ps.executeQuery()) {
                while (rs.next()) {
                    Timestamp ts = rs.getTimestamp("created_at");
                    turns.add(ChatTurn.builder()
                            .seq(rs.getInt("turn_seq"))
                            .role(rs.getString("role"))
                            .content(rs.getString("content"))
                            .toolName(rs.getString("tool_name"))
                            .toolCallId(rs.getString("tool_call_id"))
                            .meta(rs.getString("meta"))
                            .createdAt(ts == null ? null : ts.getTime())
                            .build());
                }
            }
        } catch (SQLException e) {
            log.error("[JdbcSessionStore] 读取会话失败 session={}: {}", sessionId, e.getMessage());
        }
        return turns;
    }

    @Override
    public void clear(String sessionId) {
        try (Connection conn = dataSource.getConnection();
             PreparedStatement ps = conn.prepareStatement("DELETE FROM " + table + " WHERE session_id=?")) {
            ps.setString(1, sessionId);
            ps.executeUpdate();
        } catch (SQLException e) {
            log.error("[JdbcSessionStore] 清空会话失败 session={}: {}", sessionId, e.getMessage());
        }
    }

    @Override
    public List<SessionInfo> list(String userId, int limit) {
        boolean byUser = userId != null && !userId.isBlank();
        String sql = "SELECT session_id,user_id,COUNT(*) AS c,MAX(created_at) AS u FROM " + table
                + (byUser ? " WHERE user_id=? " : " ")
                + "GROUP BY session_id,user_id ORDER BY MAX(created_at) DESC LIMIT ?";
        List<SessionInfo> result = new ArrayList<>();
        try (Connection conn = dataSource.getConnection();
             PreparedStatement ps = conn.prepareStatement(sql)) {
            int idx = 1;
            if (byUser) {
                ps.setString(idx++, userId);
            }
            ps.setInt(idx, Math.max(1, limit));
            try (ResultSet rs = ps.executeQuery()) {
                while (rs.next()) {
                    Timestamp ts = rs.getTimestamp("u");
                    result.add(SessionInfo.builder()
                            .sessionId(rs.getString("session_id"))
                            .userId(rs.getString("user_id"))
                            .turns(rs.getInt("c"))
                            .updatedAt(ts == null ? null : ts.getTime())
                            .build());
                }
            }
        } catch (SQLException e) {
            log.error("[JdbcSessionStore] 查询会话列表失败: {}", e.getMessage());
        }
        return result;
    }

    @Override
    public boolean persistent() {
        return true;
    }

    @Override
    public String backend() {
        return backend;
    }

    private int nextSeq(Connection conn, String sessionId) throws SQLException {
        try (PreparedStatement ps = conn.prepareStatement(
                "SELECT COALESCE(MAX(turn_seq),0) FROM " + table + " WHERE session_id=?")) {
            ps.setString(1, sessionId);
            try (ResultSet rs = ps.executeQuery()) {
                return rs.next() ? rs.getInt(1) : 0;
            }
        }
    }

    /** 单会话长度上限：超长会话既拖慢回放也稀释模型注意力，只保留最近 N 轮 */
    private void trim(Connection conn, String sessionId, int latestSeq) {
        int threshold = latestSeq - maxTurnsPerSession;
        if (threshold <= 0) {
            return;
        }
        try (PreparedStatement ps = conn.prepareStatement(
                "DELETE FROM " + table + " WHERE session_id=? AND turn_seq<=?")) {
            ps.setString(1, sessionId);
            ps.setInt(2, threshold);
            int deleted = ps.executeUpdate();
            if (deleted > 0) {
                log.debug("[JdbcSessionStore] 会话 {} 裁剪 {} 条历史", sessionId, deleted);
            }
        } catch (SQLException e) {
            log.warn("[JdbcSessionStore] 裁剪历史失败 session={}: {}", sessionId, e.getMessage());
        }
    }

    /** 表名只允许字母数字下划线，杜绝配置注入导致的 SQL 拼接风险 */
    private String sanitize(String prefix) {
        String p = prefix == null ? "" : prefix.replaceAll("[^a-zA-Z0-9_]", "");
        return p.isBlank() ? "agent_" : p + "_";
    }
}
